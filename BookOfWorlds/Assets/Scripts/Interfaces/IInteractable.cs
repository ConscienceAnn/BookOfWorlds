/// <summary>
/// Интерфейс для всех объектов, с которыми можно взаимодействовать
/// </summary>
public interface IInteractable
{
    /// <summary>
    /// Вызывается при взаимодействии (нажатии E)
    /// Объект сам решает, что делать: собрать ресурс, показать уведомление и т.д.
    /// </summary>
    void Interact();
}